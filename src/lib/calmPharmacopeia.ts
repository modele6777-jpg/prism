/**
 * 인덱스로 처방약 단건 조회 (1 ~ 40)
 */
export function getCalmPrescription(globalIndex: number): CalmPrescription | undefined {
  return CALM_PRESCRIPTIONS.find((p) => p.globalIndex === globalIndex);
}

/**
 * 오늘의 날짜 및 사용자 감정 상태에 기반한 맞춤 처방약 1알 자동 조제
 */
export function getDailyRecommendedPrescription(seedDateStr?: string): CalmPrescription {
  const dateStr = seedDateStr || new Date().toISOString().slice(0, 10);
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const index = (Math.abs(hash) % CALM_PRESCRIPTIONS.length) + 1;
  return getCalmPrescription(index) || CALM_PRESCRIPTIONS[0];
}

/**
 * 키워드 기반 상비약 검색 (예: '호흡', '불안', '긴장', '어깨', '수면', '생각')
 */
export function searchPrescriptions(query: string): CalmPrescription[] {
  if (!query || query.trim().length === 0) return CALM_PRESCRIPTIONS;
  const q = query.toLowerCase().trim();
  return CALM_PRESCRIPTIONS.filter(
    (p) =>
      p.title.toLowerCase().includes(q) ||
      p.subtitle.toLowerCase().includes(q) ||
      p.tag.toLowerCase().includes(q) ||
      p.purpose.toLowerCase().includes(q) ||
      p.clinicalTip.toLowerCase().includes(q) ||
      p.chapterTitle.toLowerCase().includes(q)
  );
}
