/**
 * 인덱스로 처방약 단건 조회 (1 ~ 40)
 */
export function getCalmPrescription(globalIndex: number): CalmPrescription | undefined {
  return CALM_PRESCRIPTIONS.find((p) => p.globalIndex === globalIndex);
}

/**
 * 오늘의 날짜 및 사용자 감정 상태에 기반한 맞춤 처방약 1알 자동 조제
 */
export function getDailyRecommendedPrescription(seedDateStr?: string): CalmPrescription {
  const dateStr = seedDateStr || new Date().toISOString().slice(0, 10);
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const index = (Math.abs(hash) % CALM_PRESCRIPTIONS.length) + 1;
  return getCalmPrescription(index) || CALM_PRESCRIPTIONS[0];
}

/**
 * 양피지 영시(Parchment Item) 맞춤형 40대 기법 지능형 추천
 * 각 양피지의 카테고리, 제목, 키포인트, 태그를 분석하여 40개 기법 중 가장 최적화된 처방약 1개를 추천합니다.
 */
export function recommendPrescriptionForParchment(parchment?: {
  id?: string;
  title?: string;
  keypoint?: string;
  tags?: string[];
  category?: string;
  fullText?: string;
  actionGuidance?: string;
}): CalmPrescription {
  if (!parchment) return CALM_PRESCRIPTIONS[0];

  // 1. 이미 특정 처방약 ID가 부여된 경우 (예: 'pharmacy-14')
  if (parchment.id?.startsWith('pharmacy-')) {
    const num = parseInt(parchment.id.replace('pharmacy-', ''), 10);
    const found = getCalmPrescription(num);
    if (found) return found;
  }

  // 2. 텍스트 키워드 기반 코사인 유사도/키워드 매칭
  const searchCorpus = [
    parchment.title || '',
    parchment.keypoint || '',
    (parchment.tags || []).join(' '),
    parchment.actionGuidance || '',
    parchment.fullText || ''
  ].join(' ').toLowerCase();

  let bestPrescription: CalmPrescription | null = null;
  let highestScore = -1;

  for (const p of CALM_PRESCRIPTIONS) {
    let score = 0;

    // 제목 및 부제 매칭
    if (searchCorpus.includes(p.title.toLowerCase())) score += 10;
    if (searchCorpus.includes(p.subtitle.toLowerCase())) score += 8;
    if (searchCorpus.includes(p.tag.toLowerCase())) score += 6;

    // 카테고리별 특화 가중치
    if (parchment.category === 'lucy' && (p.chapter === 1 || p.chapter === 3)) score += 4;
    if (parchment.category === 'healing' && (p.tag.includes('호흡') || p.tag.includes('이완') || p.tag.includes('감각'))) score += 5;
    if (parchment.category === 'tarot' && (p.tag.includes('관점') || p.tag.includes('가치') || p.tag.includes('선택'))) score += 5;
    if (parchment.category === 'saju' && (p.tag.includes('수용') || p.tag.includes('마음챙김') || p.tag.includes('통제'))) score += 5;
    if (parchment.category === 'muse' && (p.tag.includes('외재화') || p.tag.includes('몰입') || p.tag.includes('표현'))) score += 5;

    // 대표 키워드 매칭
    const keywords = [
      '불안', '걱정', '생각', '호흡', '신체', '긴장', '마음', '자책', '미래', '과거',
      '잠', '수면', '통제', '사람', '관계', '두려움', '스트레스', '감정', '바디스캔'
    ];
    for (const kw of keywords) {
      if (searchCorpus.includes(kw) && (p.purpose.includes(kw) || p.clinicalTip.includes(kw) || p.tag.includes(kw))) {
        score += 3;
      }
    }

    if (score > highestScore) {
      highestScore = score;
      bestPrescription = p;
    }
  }

  // 3. 점수가 충분히 높으면 추천, 점수가 미약하면 결정론적 해시로 고유 매핑
  if (bestPrescription && highestScore >= 3) {
    return bestPrescription;
  }

  const seed = parchment.id || parchment.title || 'parchment-seed';
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
    hash |= 0;
  }
  const idx = (Math.abs(hash) % CALM_PRESCRIPTIONS.length) + 1;
  return getCalmPrescription(idx) || CALM_PRESCRIPTIONS[0];
}

/**
 * 키워드 기반 상비약 검색 (예: '호흡', '불안', '긴장', '어깨', '수면', '생각')
 */
export function searchPrescriptions(query: string): CalmPrescription[] {
  if (!query || query.trim().length === 0) return CALM_PRESCRIPTIONS;
  const q = query.toLowerCase().trim();
  return CALM_PRESCRIPTIONS.filter(
    (p) =>
      p.title.toLowerCase().includes(q) ||
      p.subtitle.toLowerCase().includes(q) ||
      p.tag.toLowerCase().includes(q) ||
      p.purpose.toLowerCase().includes(q) ||
      p.clinicalTip.toLowerCase().includes(q) ||
      p.chapterTitle.toLowerCase().includes(q)
  );
}

/**
 * 처방약 실천 완료 기록 저장
 */
export function recordPrescriptionCompleted(globalIndex: number, reflectionNotes?: string): void {
  try {
    const key = 'calm_completed_prescriptions_v1';
    const raw = safeLocalStorage.getItem(key);
    const list: Array<{ globalIndex: number; timestamp: number; notes?: string }> = raw ? JSON.parse(raw) : [];
    list.unshift({
      globalIndex,
      timestamp: Date.now(),
      notes: reflectionNotes
    });
    // 최근 100건 보관
    safeLocalStorage.setItem(key, JSON.stringify(list.slice(0, 100)));
  } catch (e) {
    console.warn('[calmPharmacopeia] Failed to record completed prescription:', e);
  }
}

/**
 * 실천 완료 기록 조회
 */
export function getCompletedPrescriptionHistory(): Array<{ globalIndex: number; timestamp: number; notes?: string }> {
  try {
    const raw = safeLocalStorage.getItem('calm_completed_prescriptions_v1');
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}
