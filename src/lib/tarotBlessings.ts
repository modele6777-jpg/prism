/**
 * 🌟 카드 객체와 고민, 방향성을 바탕으로 세상에 단 하나뿐인 영혼의 축복 생성
 */
export function getCardSoulBlessing(card: any, concern?: string): string {
  if (!card) {
    return '당신이 내딛는 모든 발걸음마다 우주의 은총과 평온이 함께하며, 가장 알맞은 때에 눈부신 해답이 열리길 축복합니다.';
  }

  const cardName = card.nameKo || card.name || '운명의 카드';
  const isReversed = Boolean(card.reversed === true || card.reversed === 'true');
  const details = getTarotCardDetails(card);

  // 카드 번호 및 수트 추출 (id: 'major_0', 'wands_3' 등 또는 number/suit 프로퍼티 지원)
  let majorNum: number | null = null;
  if (typeof card.number === 'number' && card.number >= 0 && card.number <= 21) {
    majorNum = card.number;
  } else if (typeof card.id === 'string' && card.id.startsWith('major_')) {
    const parsed = parseInt(card.id.replace('major_', ''), 10);
    if (!isNaN(parsed) && parsed >= 0 && parsed <= 21) majorNum = parsed;
  }

  // 1. 메이저 아르카나일 때 (0 ~ 21)
  if (majorNum !== null && MAJOR_SOUL_BLESSINGS[majorNum]) {
    const pool = isReversed
      ? MAJOR_SOUL_BLESSINGS[majorNum].reversed
      : MAJOR_SOUL_BLESSINGS[majorNum].upright;
    if (pool && pool.length > 0) {
      // 시간/고민/랜덤 시드를 더해 매번 같은 카드를 뽑아도 다채로운 축복이 나오도록 개선
      const concernHash = (concern || '').split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
      const randomSeed = Math.floor(Math.random() * pool.length);
      const seed = Math.abs((cardName.length * 7 + majorNum * 13 + (isReversed ? 11 : 3) + concernHash + randomSeed) % pool.length);
      return pool[seed];
    }
  }

  // 2. 마이너 아르카나 수트 기반 축복 (card.suit 또는 card.type 또는 id 접두사 지원)
  let suit = String(card.suit || card.type || '').toLowerCase();
  if (!MINOR_SUIT_BLESSINGS[suit] && typeof card.id === 'string') {
    if (card.id.startsWith('wands')) suit = 'wands';
    else if (card.id.startsWith('cups')) suit = 'cups';
    else if (card.id.startsWith('swords')) suit = 'swords';
    else if (card.id.startsWith('pent')) suit = 'pentacles';
  }

  if (MINOR_SUIT_BLESSINGS[suit]) {
    const pool = isReversed ? MINOR_SUIT_BLESSINGS[suit].reversed : MINOR_SUIT_BLESSINGS[suit].upright;
    const concernHash = (concern || '').split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
    const randomSeed = Math.floor(Math.random() * pool.length);
    const seed = Math.abs((cardName.length * 3 + (isReversed ? 5 : 2) + concernHash + randomSeed) % pool.length);
    return pool[seed];
  }

  // 3. 카드 도상 상징 및 원형 기반 역동적 축복 합성
  if (isReversed) {
    const reversedBlessings = [
      `[${cardName}] 카드의 깊은 지혜처럼, 지금은 속도를 늦추고 ${details.symbolWord}의 온화한 파동으로 내면의 중심을 먼저 단단히 채워야 할 때입니다. 조급함을 내려놓을 때 당신을 지켜주는 우주의 참된 평화가 환하게 열릴 것입니다.`,
      `겉으로 드러난 장애물에 흔들리지 마세요. [${cardName}] 카드의 역방향 파동은 더 단단한 도약을 위해 잠시 숨을 고르라는 우주의 배려입니다. 당신의 내면아이는 이미 올바른 길을 알고 있습니다.`,
      `비워낼수록 더 큰 은총이 차오릅니다. [${cardName}] 카드가 이끄는 정화의 흐름 속에서 불필요한 불안을 흘려보내고, 당신만의 고유한 빛을 온전히 되찾으시길 축복합니다.`
    ];
    return reversedBlessings[Math.floor(Math.random() * reversedBlessings.length)];
  }

  const uprightBlessings = [
    `[${cardName}] 카드가 비추는 ${details.archetype}의 영적 원형과 ${details.symbolWord}의 축복이 오늘 당신의 모든 발걸음 위에 깃들길 바랍니다. 마음속 깊은 직관을 신뢰하고 당신의 길을 당당히 걸어가십시오.`,
    `당신의 가슴속에 타오르는 맑은 열정과 지혜를 믿으세요. [${cardName}] 카드의 밝은 파동이 오늘 마주할 모든 선택의 순간마다 명쾌한 통찰과 용기를 선물할 것입니다.`,
    `우주는 당신이 한 걸음 내딛을 때마다 보이지 않는 손길로 당신의 길을 밝히고 있습니다. [${cardName}] 카드의 성스러운 기운과 함께 오늘 하루도 깊은 평온과 눈부신 성취를 누리시길 축복합니다.`
  ];
  return uprightBlessings[Math.floor(Math.random() * uprightBlessings.length)];
}
