/**
 * Deterministically compute a daily index based on date string and optional seed/counter
 */
export function getDailySecretIndex(seed: number = 0): number {
  const dateStr = getTodayDateKey();
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash + seed);
}

