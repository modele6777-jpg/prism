/**
 * 도서 지식 검색 헬퍼 함수
 */
window.searchBookKnowledge = function(keyword) {
  if (!keyword || !keyword.trim()) return window.BOOK_KNOWLEDGE.chapters;
  const q = keyword.trim().toLowerCase();

  const results = [];
  window.BOOK_KNOWLEDGE.chapters.forEach(ch => {
    const matchedConcepts = ch.concepts.filter(c => 
      c.title.toLowerCase().includes(q) ||
      c.desc.toLowerCase().includes(q) ||
      c.quote.toLowerCase().includes(q) ||
      c.badge.toLowerCase().includes(q) ||
      (c.actionTip && c.actionTip.toLowerCase().includes(q))
    );

    if (ch.title.toLowerCase().includes(q) || ch.summary.toLowerCase().includes(q) || matchedConcepts.length > 0) {
      results.push({
        ...ch,
        matchedConcepts: matchedConcepts.length > 0 ? matchedConcepts : ch.concepts
      });
    }
  });

  return results;
};
